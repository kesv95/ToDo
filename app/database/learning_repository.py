import os
import psycopg
from psycopg.rows import dict_row


def get_db():
    """Neon PostgreSQL에 연결한다."""
    database_url = os.getenv("DATABASE_URL")

    if not database_url:
        raise RuntimeError("DATABASE_URL 환경 변수가 설정되지 않았습니다.")

    return psycopg.connect(
        database_url,
        row_factory=dict_row,
        connect_timeout=10
    )


def init_db():
    """필요한 테이블과 인덱스를 생성한다."""
    with get_db() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id TEXT PRIMARY KEY,
                name TEXT NOT NULL DEFAULT '',
                email TEXT NOT NULL DEFAULT '',
                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS learning_records (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                category INTEGER NOT NULL,
                study INTEGER NOT NULL,
                plan INTEGER NOT NULL,
                review INTEGER NOT NULL,
                score INTEGER NOT NULL,
                diagnosis TEXT NOT NULL,
                advice TEXT NOT NULL,
                created_at TEXT NOT NULL
            )
        """)

        conn.execute("""
            ALTER TABLE learning_records
            ADD COLUMN IF NOT EXISTS user_id TEXT
            REFERENCES users(id)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS
            idx_learning_records_user_id_id
            ON learning_records(user_id, id DESC)
        """)


def save_user(user_id, name, email):
    """Google 로그인 사용자를 저장하거나 정보를 갱신한다."""
    with get_db() as conn:
        conn.execute("""
            INSERT INTO users (id, name, email)
            VALUES (%s, %s, %s)
            ON CONFLICT (id) DO UPDATE SET
                name = EXCLUDED.name,
                email = EXCLUDED.email
        """, (user_id, name, email))


def get_records(user_id, limit=10):
    """특정 회원의 최근 진단 기록을 조회한다."""
    if not user_id:
        return []

    with get_db() as conn:
        result = conn.execute("""
            SELECT *
            FROM learning_records
            WHERE user_id = %s
            ORDER BY id DESC
            LIMIT %s
        """, (user_id, limit))

        return result.fetchall()


def save_record(
    user_id,
    category,
    study,
    plan,
    review,
    score,
    diagnosis,
    advice,
    created_at
):
    """로그인한 회원의 진단 기록을 저장한다."""
    if not user_id:
        raise ValueError("로그인한 사용자 ID가 필요합니다.")

    with get_db() as conn:
        user = conn.execute(
            "SELECT id FROM users WHERE id = %s",
            (user_id,)
        ).fetchone()

        if user is None:
            raise ValueError(
                "회원 정보가 데이터베이스에 없습니다. "
                "다시 로그인해 주세요."
            )

        conn.execute("""
            INSERT INTO learning_records (
                user_id,
                category,
                study,
                plan,
                review,
                score,
                diagnosis,
                advice,
                created_at
            )
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
        """, (
            user_id,
            category,
            study,
            plan,
            review,
            score,
            diagnosis,
            advice,
            created_at
        ))
